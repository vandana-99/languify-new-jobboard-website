const hook = process.env.CLOUDFLARE_DEPLOY_HOOK;
if (!hook) throw new Error('Add the CLOUDFLARE_DEPLOY_HOOK repository secret, then run this workflow again.');
const url = new URL(hook);
if (url.protocol !== 'https:' || url.hostname !== 'api.cloudflare.com' || !url.pathname.startsWith('/client/v4/pages/webhooks/deploy_hooks/')) throw new Error('Use the deploy hook URL generated by your separate Cloudflare Pages project.');
let response;
try { response = await fetch(hook, { method: 'POST', redirect: 'error', signal: AbortSignal.timeout(30000) }); }
catch { throw new Error('Could not request a Cloudflare deployment. Retry the workflow; do not paste the secret URL into logs.'); }
if (!response.ok) throw new Error(`Cloudflare rejected the deployment request (HTTP ${response.status}).`);
const data = await response.json();
if (data.success === false) throw new Error('Cloudflare did not accept the deployment request.');
console.log('Cloudflare deployment requested. Check Cloudflare for the final build/deployment result.');
